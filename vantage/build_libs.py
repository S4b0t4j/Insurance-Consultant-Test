#!/usr/bin/env python3
"""Rebuild vantage-libs.js from vendor/. Only needed if a library is upgraded.

Usage: python3 vantage/build_libs.py
Output: vantage/vantage-libs.js (keep it next to VANTAGE.html)
"""
import os, re

HERE = os.path.dirname(os.path.abspath(__file__))
V = os.path.join(HERE, 'vendor')

def rd(name):
    with open(os.path.join(V, name), encoding='utf-8') as f:
        return f.read().strip()

parts = [
    ('d3 7.8.5 (ISC)', rd('d3.min.js')),
    ('topojson-client 3.1.0 (ISC)', rd('topojson-client.min.js')),
    ('SheetJS xlsx 0.18.5 (Apache-2.0)', rd('xlsx.full.min.js')),
    ('us-atlas 3.0.1 states (ISC)', 'window.US_STATES_10M=' + rd('states-10m.json') + ';'),
    ('us-atlas 3.0.1 counties (ISC)', 'window.US_COUNTIES_10M=' + rd('counties-10m.json') + ';'),
    ('us-zips 2022.9.1, Census ZCTA centroids (MIT): {zip:[lat,lng]}', 'window.ZIP_CENTROIDS=' + rd('zip_centroids.json') + ';'),
]
out = ['/* VANTAGE offline library bundle. Generated by build_libs.py. Do not edit by hand. */']
for label, code in parts:
    out.append('\n/* ===== %s ===== */\n;%s\n' % (label, code))
path = os.path.join(HERE, 'vantage-libs.js')
with open(path, 'w', encoding='utf-8') as f:
    f.write('\n'.join(out))
print('Built %s (%.1f MB)' % (path, os.path.getsize(path) / 1e6))
